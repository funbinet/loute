import '../models/report_model.dart';
import '../utils/format_utils.dart';

class CveEngine {
  static String render(ReportPayload payload) {
    final cves = <String>{};
    // Standard CVE syntax: CVE-YYYY-NNNNNNN
    final regex = RegExp(r'CVE-\d{4}-\d{4,7}', caseSensitive: false);

    // 1. Capture ALL CVE occurrences across findings
    for (final finding in payload.findings) {
      for (final value in finding.values) {
        if (value != null) {
          final matches = regex.allMatches(value.toString());
          for (final match in matches) {
            cves.add(match.group(0)!.toUpperCase());
          }
        }
      }
    }

    // 2. Capture ALL CVE occurrences in the raw stdout/stderr output
    final strippedOutput = FormatUtils.stripHtmlTags(payload.rawOutput);
    final rawMatches = regex.allMatches(strippedOutput);
    for (final match in rawMatches) {
      cves.add(match.group(0)!.toUpperCase());
    }

    // 3. Sort CVEs Chronologically (Newest Years and Highest IDs First)
    final sortedCves = cves.toList();
    sortedCves.sort((a, b) {
      final aParts = a.split('-');
      final bParts = b.split('-');
      if (aParts.length < 3 || bParts.length < 3) return a.compareTo(b);
      
      final aYear = int.tryParse(aParts[1]) ?? 0;
      final bYear = int.tryParse(bParts[1]) ?? 0;
      if (aYear != bYear) {
        return bYear.compareTo(aYear); // Descending Year
      }
      
      final aNum = int.tryParse(aParts[2]) ?? 0;
      final bNum = int.tryParse(bParts[2]) ?? 0;
      return bNum.compareTo(aNum); // Descending ID number
    });

    final buffer = StringBuffer();
    buffer.writeln('================================================================================');
    buffer.writeln('                              LOUTE CVE REPORT                                  ');
    buffer.writeln('                       Autonomous Bug Bounty Framework                          ');
    buffer.writeln('================================================================================');
    buffer.writeln('Action Name: ${payload.actionName}');
    buffer.writeln('Report ID  : ${payload.id}');
    buffer.writeln('Timestamp  : ${payload.timestamp.toUtc().toIso8601String()} UTC');
    buffer.writeln('--------------------------------------------------------------------------------');
    
    buffer.writeln(' [METRICS SUMMARY]');
    buffer.writeln(' ├─ Total Identified CVEs: ${sortedCves.length}');
    
    // Group CVEs by Year for high-level insight
    final Map<String, int> yearCounts = {};
    for (final cve in sortedCves) {
      final parts = cve.split('-');
      if (parts.length >= 2) {
        final year = parts[1];
        yearCounts[year] = (yearCounts[year] ?? 0) + 1;
      }
    }
    
    if (yearCounts.isNotEmpty) {
      final years = yearCounts.keys.toList()..sort((a, b) => b.compareTo(a));
      for (var i = 0; i < years.length; i++) {
        final isLast = i == years.length - 1;
        final branch = isLast ? ' └─ ' : ' ├─ ';
        buffer.writeln('${branch}Year ${years[i]} Volume   : ${yearCounts[years[i]]} CVEs');
      }
    } else {
      buffer.writeln(' └─ No chronological groups');
    }
    
    buffer.writeln('--------------------------------------------------------------------------------');

    if (sortedCves.isEmpty) {
      buffer.writeln(' NO CVE IDENTIFIERS DETECTED IN SCAN LOGS OR FINDINGS.');
    } else {
      buffer.writeln(' DETECTED VULNERABILITY REFERENCES:');
      buffer.writeln();
      for (final cve in sortedCves) {
        buffer.writeln('   * $cve');
        buffer.writeln('     Ref: https://nvd.nist.gov/vuln/detail/$cve');
        buffer.writeln();
      }
    }
    buffer.writeln('================================================================================');
    buffer.writeln('              Generated by LOUTE Autonomous Operations Signature                ');
    buffer.writeln('================================================================================');

    return buffer.toString();
  }
}
